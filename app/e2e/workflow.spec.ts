import { expect, test, type Page, type Locator } from '@playwright/test';
import path from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';

const shots = path.resolve('screenshots');
async function shot(page: Page, name: string, focus?: Locator) {
  if (focus) await focus.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(shots, name), animations: 'disabled' });
}

test('博主从注册、上传到笔记与视频的完整合作流程', async ({ page }) => {
  await mkdir(shots, { recursive: true });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const polls: number[] = [];
  page.on('request', request => { if (request.url().endsWith('/state')) polls.push(Date.now()); });
  await page.goto('/');
  await page.getByRole('button', { name: '注册', exact: true }).click();
  await page.getByLabel('怎么称呼你', { exact: true }).fill('小序');
  const username = `creator_${Date.now()}`;
  await page.getByLabel('用户名', { exact: true }).fill(username);
  await page.getByLabel('密码', { exact: true }).fill('Demo-only-2026');
  await shot(page, '01-register.png');
  await page.getByRole('button', { name: '创建账号，开始创作', exact: true }).click();
  await expect(page.getByText('小序的创作间')).toBeVisible();
  await shot(page, '02-projects-empty.png');
  await page.getByRole('button', { name: '新建品牌合作', exact: true }).click();
  await page.getByLabel('项目名称', { exact: true }).fill('把秋天穿成一杯燕麦拿铁');
  await page.getByLabel('合作品牌', { exact: true }).fill('SOFT STUDIO');
  await page.getByLabel('品牌需求', { exact: true }).fill('米白亚麻衬衫与浅蓝牛仔裤，想突出自然面料和松弛感。适合咖啡店、街头的秋日穿搭，文案要像朋友分享。');
  const chooser = page.waitForEvent('filechooser');
  await page.getByTestId('upload-garments').click();
  await (await chooser).setFiles([path.resolve('../docs/spike/inputs.jpg'), path.resolve('../docs/spike/t-wan-v.jpg')]);
  await expect(page.getByRole('button', { name: '移除衣服图 2' })).toBeVisible();
  const modelChooser = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: '上传我的照片', exact: true }).click();
  await (await modelChooser).setFiles(path.resolve('../docs/spike/inputs.jpg'));
  await expect(page.getByRole('button', { name: '更换我的照片', exact: true })).toBeVisible();
  await shot(page, '03-new-project-uploaded.png', page.getByTestId('upload-garments'));
  await page.getByRole('button', { name: '开始聊灵感', exact: true }).click();
  const direction = page.getByTestId('direction-direction_city');
  await expect(direction).toBeVisible();
  await shot(page, '04-garments-and-directions.png', direction);
  // 自由文本也经过同一 SSE 入口，随后再执行明确确认。
  await page.getByTestId('chat-input').fill('希望整体再松弛一点。');
  await page.getByTestId('send-message').click();
  await expect(direction).toBeEnabled();
  await direction.click();
  await expect(page.getByTestId('confirm-script')).toBeEnabled();
  await shot(page, '05-script-confirmation.png', page.getByTestId('confirm-script'));
  await page.getByTestId('confirm-script').click();
  await expect(page.getByText('画面生成中').first()).toBeVisible();
  await shot(page, '06-images-generating.png', page.getByText('画面生成中').first());
  await expect(page.getByTestId('approve-images')).toBeEnabled();
  await shot(page, '07-images-ready.png', page.getByText('你的穿搭影像'));
  const edit = page.getByTestId(/^edit-image-/).first();
  const firstId = (await edit.getAttribute('data-testid'))!.replace('edit-image-', '');
  await edit.click();
  await page.getByTestId('edit-instruction').fill('把衬衫塞进裤腰，背景更明亮一点。');
  await shot(page, '08-edit-image.png');
  await page.getByTestId('submit-edit').click();
  await expect(page.getByText('v2 新版')).toBeVisible();
  await expect(page.getByTestId('approve-images')).toBeEnabled();
  await shot(page, '09-image-new-version.png', page.getByText('你的穿搭影像'));
  const selectedIds = await page.getByTestId(/^move-up-/).evaluateAll(nodes => nodes.map(node => node.getAttribute('data-testid')!.replace('move-up-', '')));
  // 默认选最新版本；向后移动封面，验证发送的图片顺序会被保留。
  expect(selectedIds.length).toBeGreaterThanOrEqual(3);
  const firstSortDown = page.getByTestId(/^move-down-/).first();
  await firstSortDown.click();
  const orderedIds = await page.getByTestId(/^move-up-/).evaluateAll(nodes => nodes.map(node => node.getAttribute('data-testid')!.replace('move-up-', '')));
  await shot(page, '10-selected-order.png', page.getByTestId('approve-images'));
  const noteResponse = page.waitForResponse(response => response.url().endsWith('/state') && response.request().method() === 'GET');
  await page.getByTestId('approve-images').click();
  await expect(page.getByTestId('preview-note')).toBeVisible();
  const noteState = await (await noteResponse).json();
  expect(noteState.note.image_ids).toEqual(orderedIds);
  await shot(page, '11-note-card.png', page.getByTestId('preview-note'));
  await page.getByTestId('preview-note').click();
  await expect(page.getByTestId('note-title')).toBeVisible();
  await shot(page, '12-note-preview.png');
  await page.getByTestId('copy-note').click();
  await expect(page.getByText('文案已复制，可以去发布啦。')).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByTestId('save-images').click();
  await (await download).saveAs(path.resolve('test-results/saved-image.jpg'));
  await page.getByRole('button', { name: '返回', exact: true }).click();
  await expect(page.getByTestId('confirm-video')).toBeEnabled();
  await page.getByTestId('confirm-video').click();
  await expect(page.getByTestId('play-video')).toBeVisible();
  await shot(page, '13-video-ready.png', page.getByTestId('play-video'));
  await page.getByTestId('play-video').click();
  const video = page.locator('video').last();
  await expect(video).toBeVisible();
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).currentTime)).toBeGreaterThanOrEqual(1);
  await shot(page, '14-video-playing.png', video);
  await page.reload();
  await expect(page.getByTestId('preview-note')).toBeVisible();
  await page.getByRole('button', { name: '返回', exact: true }).click();
  await expect(page.getByRole('button', { name: '打开项目 把秋天穿成一杯燕麦拿铁' })).toBeVisible();
  await shot(page, '15-project-completed.png', page.getByRole('button', { name: '打开项目 把秋天穿成一杯燕麦拿铁' }));
  // API 401 必须清除会话并回登录。
  await page.route('**/api/projects', route => route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ error: { code: 'UNAUTHORIZED', message: '登录已过期，请重新登录。' } }) }));
  await page.reload();
  await expect(page.getByRole('button', { name: '登录，继续创作' })).toBeVisible();
  await shot(page, '16-expired-session.png');
  await page.unroute('**/api/projects');
  await page.getByLabel('用户名', { exact: true }).fill(username);
  await page.getByLabel('密码', { exact: true }).fill('Demo-only-2026');
  await page.getByRole('button', { name: '登录，继续创作' }).click();
  await expect(page.getByText('小序的创作间')).toBeVisible();
  // 断网错误可重试，恢复后仍能找回项目。
  await page.route('**/api/projects', route => route.abort('internetdisconnected'));
  await page.reload();
  await expect(page.getByText('连接不到服务器，请检查网络和服务器地址。')).toBeVisible();
  await shot(page, '17-network-error.png', page.getByText('连接不到服务器，请检查网络和服务器地址。'));
  await page.unroute('**/api/projects');
  await page.getByRole('button', { name: '重试', exact: true }).click();
  await expect(page.getByRole('button', { name: '打开项目 把秋天穿成一杯燕麦拿铁' })).toBeVisible();
  await shot(page, '18-network-recovered.png', page.getByRole('button', { name: '打开项目 把秋天穿成一杯燕麦拿铁' }));
  expect(errors).toEqual([]);
  await writeFile(path.join(shots, 'evidence.json'), JSON.stringify({ viewport: '390×844', passedAt: new Date().toISOString(), firstEditedImage: firstId, selectedOrder: orderedIds, stateRequests: polls.length, videoPlayed: true, pageErrors: errors }, null, 2));
});
